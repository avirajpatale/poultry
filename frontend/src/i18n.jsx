// ---------- Context ----------
const LangCtx = createContext(null)

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => localStorage.getItem('farm_lang') || 'mr')
  const setLang = (l) => { localStorage.setItem('farm_lang', l); setLangState(l) }
  const t = (key, vars) => {
    let s = STR[lang]?.[key] ?? STR.en[key] ?? key
    if (vars) for (const k in vars) s = s.replaceAll(`{${k}}`, vars[k])
    return s
  }
  return <LangCtx.Provider value={{ lang, setLang, t }}>{children}</LangCtx.Provider>
}

export const useLang = () => useContext(LangCtx)

// ---------- Small EN/मर toggle ----------
export function LangSwitch() {
  const { lang, setLang } = useLang()
  return (
    <div className="btn-group btn-group-sm" role="group" title="Language / भाषा">
      <button type="button" className={`btn ${lang === 'en' ? 'btn-success' : 'btn-outline-secondary'}`}
        onClick={() => setLang('en')}>EN</button>
      <button type="button" className={`btn ${lang === 'mr' ? 'btn-success' : 'btn-outline-secondary'}`}
        onClick={() => setLang('mr')}>मराठी</button>
    </div>
  )
}
